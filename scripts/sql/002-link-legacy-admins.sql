-- ---------------------------------------------------------------------------
-- STEP 4 — Confirm at least one superadmin exists before you log out.
-- If this returns 0, you are about to lock yourself out of the admin panel.
-- ---------------------------------------------------------------------------

SELECT COUNT(*) AS superadmin_count
FROM   users
WHERE  role = 'superadmin';
